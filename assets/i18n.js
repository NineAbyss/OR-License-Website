/* Translate presentation text while leaving result data and chart geometry intact. */
(() => {
  'use strict';
  const dictionary = window.OR_LICENSE_ZH || {};
  const key = 'or-license-language';
  const root = document.documentElement;
  const normalize = value => value.replace(/\s+/g, ' ').trim();
  const textOriginals = new WeakMap();
  const attributeOriginals = new WeakMap();
  const searchOriginals = new WeakMap();
  const imageOriginals = new WeakMap();
  // Keep data-* values in their original language so dynamic chart readouts
  // always enter the translation layer as English, even after repeated toggles.
  const attrs = ['title', 'aria-label', 'placeholder', 'alt'];
  let language = 'en';
  try { if (localStorage.getItem(key) === 'zh-CN') language = 'zh-CN'; } catch (_) {}

  // Templates cover numeric hover text generated by the original chart scripts.
  const phrases = {
    'Infeasible deliveries': '不可行交付',
    'Model infeasible rate': '模型不可行率',
    'of annotated error events': '（占已标注错误事件）',
    'of error events': '（占错误事件）',
    'confirmed-resolution proportion': '已确认解决比例',
    'Question share': '提问占比',
    'approximate vector reading': '矢量图近似读数',
    'vector-digitized': '矢量图数字化读数',
    'printed label': '图中标注',
    'stage quality': '阶段质量',
    'approximately': '约',
    'rounded': '四舍五入',
    'Not formed H': '未形成 H',
    'Stopped at': '止于',
    'Completed HCAEU': '完成 HCAEU',
    'Problem understanding': '问题理解',
    'Data and parameter mapping': '数据与参数映射',
    'Decision semantics': '决策语义',
    'Constraint coverage': '约束覆盖',
    'Dynamic consistency': '动态一致性',
    'Uncertainty semantics': '不确定性语义',
    'Objective semantics': '目标语义',
    'Implementation correctness': '实现正确性'
  };
  const fragments = Object.entries({...dictionary, ...phrases})
    .filter(([en, zh]) => en !== zh && en.length > 3)
    .sort((a, b) => b[0].length - a[0].length);
  function translate(value) {
    const normalized = normalize(value);
    if (Object.prototype.hasOwnProperty.call(dictionary, normalized)) {
      return value.replace(/\S[\s\S]*\S|\S/, dictionary[normalized]);
    }
    if (/^\d+ of \d+ tasks$/.test(normalized)) {
      return normalized.replace(/^(\d+) of (\d+) tasks$/, '$1 / $2 项任务');
    }
    const turn = normalized.match(/^Turn (\d+) of (\d+) · (.+)$/);
    if (turn) return `第 ${turn[1]} / ${turn[2]} 轮 · ${translate(turn[3])}`;
    if (/^All \d+ turns · Authored dialogue$/.test(normalized)) {
      return normalized.replace(/^All (\d+) turns · Authored dialogue$/, '全部 $1 轮 · 编写的示例对话');
    }
    if (/^(TASK|CASE) \d+$/.test(normalized)) return normalized.replace(/^(TASK|CASE)/, '任务');
    // Only use fragments for composite chart tooltips, never for prose or model names.
    if (normalized.includes(';') || /Infeasible deliveries|of error events|stage quality/.test(normalized)) {
      let result = value;
      for (const [en, zh] of fragments) result = result.split(en).join(zh);
      return result.replace(/of (\d+) tasks/g, '（占 $1 项任务）');
    }
    return value;
  }
  function translatedState(current, previous) {
    // Dynamic UI can replace an existing text node or attribute with a fresh English value.
    if (!previous || (current !== previous.en && current !== previous.zh)) {
      return {en: current, zh: translate(current)};
    }
    return previous;
  }
  function ignored(element) {
    return element.closest('script, style, code, pre, .header-controls, [translate="no"]');
  }
  function renderText() {
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!node.parentElement || ignored(node.parentElement) || !node.textContent.trim()) continue;
      const state = translatedState(node.textContent, textOriginals.get(node));
      textOriginals.set(node, state);
      const desired = language === 'zh-CN' ? state.zh : state.en;
      if (node.textContent !== desired) node.textContent = desired;
    }
    document.querySelectorAll(attrs.map(attr => `[${attr}]`).join(',')).forEach(element => {
      if (ignored(element)) return;
      let originals = attributeOriginals.get(element);
      if (!originals) { originals = {}; attributeOriginals.set(element, originals); }
      for (const attr of attrs) {
        if (!element.hasAttribute(attr)) continue;
        const state = translatedState(element.getAttribute(attr), originals[attr]);
        originals[attr] = state;
        const desired = language === 'zh-CN' ? state.zh : state.en;
        if (element.getAttribute(attr) !== desired) element.setAttribute(attr, desired);
      }
    });
  }
  function renderCases() {
    document.querySelectorAll('.task-card[data-case]').forEach(card => {
      if (!searchOriginals.has(card)) searchOriginals.set(card, card.dataset.case);
      card.dataset.case = searchOriginals.get(card) + ' ' + card.textContent.toLowerCase();
    });
    document.querySelectorAll('.case-schematic img[data-src-zh]').forEach(img => {
      const anchor = img.closest('a');
      if (!imageOriginals.has(img)) imageOriginals.set(img, {src: img.getAttribute('src'), href: anchor.getAttribute('href')});
      const original = imageOriginals.get(img);
      const src = language === 'zh-CN' ? img.dataset.srcZh : original.src;
      const href = language === 'zh-CN' ? img.dataset.srcZh : original.href;
      if (img.getAttribute('src') !== src) img.setAttribute('src', src);
      if (anchor.getAttribute('href') !== href) anchor.setAttribute('href', href);
    });
  }
  const observer = new MutationObserver(() => {
    if (queued) return;
    queued = true;
    requestAnimationFrame(() => { queued = false; render(); });
  });
  let queued = false;
  function observe() {
    observer.observe(document.documentElement, {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: attrs
    });
  }
  function render() {
    observer.disconnect();
    renderText();
    renderCases();
    observe();
  }
  function apply() {
    root.lang = language;
    const button = document.querySelector('.language-toggle');
    if (button) {
      button.textContent = language === 'zh-CN' ? 'EN' : '中文';
      button.setAttribute('aria-label', language === 'zh-CN' ? 'Switch to English' : '切换到中文版');
      button.setAttribute('title', language === 'zh-CN' ? 'Switch to English' : '切换到中文版');
      button.setAttribute('lang', language === 'zh-CN' ? 'en' : 'zh-CN');
    }
    render();
    // Reapply an active catalogue filter against the newly translated search index.
    const search = document.getElementById('case-search');
    if (search?.value) search.dispatchEvent(new Event('input', {bubbles: true}));
    document.dispatchEvent(new Event('or:languagechange'));
  }
  document.querySelector('.language-toggle')?.addEventListener('click', () => {
    language = language === 'zh-CN' ? 'en' : 'zh-CN';
    try { localStorage.setItem(key, language); } catch (_) {}
    apply();
  });
  window.addEventListener('storage', event => {
    if (event.key !== key && event.key !== null) return;
    language = event.newValue === 'zh-CN' ? 'zh-CN' : 'en';
    apply();
  });
  apply();
})();
